"""Encodes the made-up contact portraits of assets/demo/ for the demo build.

Writes resources/demo/portraits~<platform>.bin: the portraits one after
the other, in the pixel format the phone sends (see PROTOCOL.md), at the largest
photo size the platform asks for, dithered the way Photos.kt does it. They stay
in flash, read a row at a time. src/c/demo_photos.h gives their size and
order. Needs rsvg-convert and ImageMagick.

Usage: uv run tools/make_demo_photos.py
"""

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "assets" / "demo"
HEADER = ROOT / "src" / "c" / "demo_photos.h"
RESOURCES = ROOT / "resources" / "demo"

# Contact id in demo.c, portrait name.
PORTRAITS = [(1, "alice"), (2, "hugo"), (3, "lea")]

# Photo edge and format per platform: Time 2 and Round 2 default to the large text
# size, the others to medium (see ui.c).
PLATFORMS = {
    "basalt": (60, "color"),
    "chalk": (60, "color"),
    "diorite": (60, "mono"),
    "emery": (84, "color"),
    "flint": (60, "mono"),
    "gabbro": (84, "color"),
}


def rgba(svg: Path, size: int) -> bytes:
    png = subprocess.run(
        ["rsvg-convert", "-w", str(size), "-h", str(size), str(svg)], check=True, capture_output=True
    ).stdout
    return subprocess.run(
        ["convert", "png:-", "-background", "white", "-alpha", "remove", "-depth", "8", "rgba:-"],
        input=png,
        check=True,
        capture_output=True,
    ).stdout


def inside_circle(x: int, y: int, size: int) -> bool:
    center = (size - 1) / 2
    radius = size / 2
    return (x - center) ** 2 + (y - center) ** 2 <= radius * radius


def dither(values: list[float], size: int, max_level: int) -> list[int]:
    """Floyd-Steinberg down to 0..max_level, as Photos.dither()."""
    step = 255 / max_level
    out = [0] * (size * size)
    for y in range(size):
        for x in range(size):
            i = y * size + x
            level = min(max(int(values[i] / step + 0.5), 0), max_level)
            out[i] = level
            error = values[i] - level * step
            if x + 1 < size:
                values[i + 1] += error * 7 / 16
            if y + 1 < size:
                if x > 0:
                    values[i + size - 1] += error * 3 / 16
                values[i + size] += error * 5 / 16
                if x + 1 < size:
                    values[i + size + 1] += error * 1 / 16
    return out


def color(pixels: bytes, size: int) -> bytes:
    levels = [dither([float(pixels[i * 4 + c]) for i in range(size * size)], size, 3) for c in range(3)]
    return bytes(
        ((3 if inside_circle(i % size, i // size, size) else 0) << 6)
        | (levels[0][i] << 4)
        | (levels[1][i] << 2)
        | levels[2][i]
        for i in range(size * size)
    )


def mono(pixels: bytes, size: int) -> bytes:
    luma = [
        0.299 * pixels[i * 4] + 0.587 * pixels[i * 4 + 1] + 0.114 * pixels[i * 4 + 2]
        for i in range(size * size)
    ]
    levels = dither(luma, size, 1)
    row_bytes = (size + 7) // 8
    out = bytearray(row_bytes * size)
    for y in range(size):
        for x in range(size):
            if levels[y * size + x] == 1 or not inside_circle(x, y, size):
                out[y * row_bytes + x // 8] |= 1 << (x % 8)
    return bytes(out)


def main() -> None:
    RESOURCES.mkdir(parents=True, exist_ok=True)
    for platform, (size, kind) in PLATFORMS.items():
        data = b""
        for _, name in PORTRAITS:
            pixels = rgba(SOURCES / "avatar_{}.svg".format(name), size)
            data += color(pixels, size) if kind == "color" else mono(pixels, size)
        target = RESOURCES / "portraits~{}.bin".format(platform)
        target.write_bytes(data)
        print("Wrote", target.relative_to(ROOT))
    contacts = ", ".join(str(contact) for contact, _ in PORTRAITS)
    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "// Generated by tools/make_demo_photos.py from assets/demo/avatar_*.svg.",
        "// Size of the made-up portraits in RESOURCE_ID_DEMO_PORTRAITS, and their contacts in order.",
        "#pragma once",
        "",
        "#if defined(PBL_PLATFORM_EMERY) || defined(PBL_PLATFORM_GABBRO)",
        "#define DEMO_PHOTO_SIZE 84",
        "#else",
        "#define DEMO_PHOTO_SIZE 60",
        "#endif",
        "",
        "static const int32_t DEMO_PHOTO_CONTACTS[] = { " + contacts + " };",
    ]
    HEADER.write_text("\n".join(lines) + "\n")
    print("Wrote", HEADER.relative_to(ROOT))


if __name__ == "__main__":
    main()
